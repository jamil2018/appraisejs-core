import { externalEffectAttempts } from './fixtures/codex-app-server-m02-ta-matrix-r23-composed/no-external-effects.mjs'
import assert from 'node:assert/strict'
import fs from 'node:fs/promises'
import { createHash } from 'node:crypto'
import test from 'node:test'
import { join } from 'node:path'
import { checkR24GeneratedSpecimen } from './fixtures/codex-app-server-m02-ta-r24-specimen-02/specimencheck.mjs'
import {
  dispatchMatrixEntrypoint,
  readFixedReceipt,
} from './fixtures/codex-app-server-m02-ta-matrix-r24/entrypoint.mjs'
import {
  MATRIX_MANIFEST,
  verifyR24MatrixPreparation,
} from './fixtures/codex-app-server-m02-ta-matrix-r24/preparation.mjs'

const sha = bytes => createHash('sha256').update(bytes).digest('hex')

test('additive specimen reads frozen generated bytes and strict review without native authority', async () => {
  const directory = await fs.mkdtemp('/private/tmp/m02-r24-specimen-02-')
  const testEnvironment = process.env
  // node:test adds its own metadata. This imported offline test supplies the fixed environment;
  // it is not another actual host precheck or evidence of host environment enforcement.
  process.env = { PATH: '/usr/bin:/bin', LANG: 'C' }
  try {
    const specimenPath = join(directory, 'synthetic-decision.json')
    const result = await checkR24GeneratedSpecimen({ specimenPath })
    assert.equal(result.status, 'SYNTHETIC_R24_SPECIMEN_PRECHECK_PASSED_NO_RUNTIME_AUTHORITY')
    assert.equal(result.nativeEffects, false)
    const prepared = await verifyR24MatrixPreparation()
    const original = JSON.parse(await fs.readFile(specimenPath, 'utf8'))
    assert.deepEqual(original.r23TerminalEvidence, prepared.manifest.r23TerminalEvidence)
    assert.deepEqual(original.continuingImplementationAuthority, prepared.manifest.continuingImplementationAuthority)
    assert.equal(original.exactArtifactUserApprovalClaimed, false)
    assert.equal(original.specimenOnly, true)
    let effects = 0
    const forbidden = async () => {
      effects++
      throw new Error('external effect attempted')
    }
    const args = [
      '--precheck',
      MATRIX_MANIFEST,
      prepared.manifestDigest,
      prepared.manifestFileSha256,
      result.reviewSha256,
      result.specimenSha256,
    ]
    const ports = {
      programPath: join(process.cwd(), 'scripts/tests/fixtures/codex-app-server-m02-ta-matrix-r24/entrypoint.mjs'),
      verify: async () => prepared,
      syntheticSpecimen: true,
      readDecision: () => readFixedReceipt(specimenPath),
      verifyHostFile: forbidden,
      verifyPrior: forbidden,
      loadAddon: forbidden,
      run: forbidden,
    }
    // Synthetic authority must remain unusable for native --run even with valid bytes and hashes.
    args[0] = '--run'
    await assert.rejects(dispatchMatrixEntrypoint(args, ports), /continuing R24 implementation authority/)
    args[0] = '--precheck'
    for (const key of [
      'r23TerminalEvidence',
      'continuingImplementationAuthority',
      'exactArtifactUserApprovalClaimed',
    ]) {
      const changed = structuredClone(original)
      delete changed[key]
      const bytes = Buffer.from(`${JSON.stringify(changed, null, 2)}\n`)
      await fs.writeFile(specimenPath, bytes)
      args[5] = sha(bytes)
      await assert.rejects(dispatchMatrixEntrypoint(args, ports), /continuing R24 implementation authority/)
    }
    assert.equal(effects, 0)
    assert.deepEqual(externalEffectAttempts, [])
  } finally {
    process.env = testEnvironment
    // Only this test's freshly created disposable directory; no campaign/historical cleanup.
    await fs.rm(directory, { recursive: true, force: true })
  }
})

test('specimen cannot write to a campaign root or non-disposable path', async () => {
  for (const specimenPath of ['/private/tmp/appraise-m02-ta-matrix-p10/decision.json', '/var/not-a-specimen.json'])
    await assert.rejects(checkR24GeneratedSpecimen({ specimenPath }), /distinct disposable/)
  assert.deepEqual(externalEffectAttempts, [])
})
