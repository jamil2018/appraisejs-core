import { createHash } from 'node:crypto'
import { readdir, readFile, writeFile } from 'node:fs/promises'
import { join, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(fileURLToPath(new URL('..', import.meta.url)))
const runtimeSource = join(root, 'packages/cucumber-runtime/src')
const manifest = join(runtimeSource, 'operations/handler-source-hash.ts')

function isRuntimeSource(entry, path) {
  return entry.isFile() && entry.name.endsWith('.ts') && !entry.name.endsWith('.test.ts') && path !== manifest
}

async function sourceFiles(directory) {
  const entries = await readdir(directory, { withFileTypes: true })
  const nested = await Promise.all(
    entries.map(async entry => {
      const path = join(directory, entry.name)
      if (entry.isDirectory()) return sourceFiles(path)
      return isRuntimeSource(entry, path) ? [path] : []
    }),
  )
  return nested.flat()
}

const files = (await sourceFiles(runtimeSource)).sort((left, right) => left.localeCompare(right))
const digest = createHash('sha256')
for (const path of files) {
  digest.update(relative(runtimeSource, path).replaceAll('\\', '/'))
  digest.update('\0')
  digest.update(await readFile(path))
  digest.update('\0')
}
const expected = `// Generated by scripts/generate-operation-handler-source-hash.mjs.\nexport const handlerSourceHash = 'sha256:${digest.digest('hex')}' as const\n`
if (process.argv.includes('--check')) {
  const actual = await readFile(manifest, 'utf8').catch(() => '')
  if (actual !== expected) {
    console.error('Operation handler source hash is stale. Run npm run operation:projections.')
    process.exitCode = 1
  }
} else {
  await writeFile(manifest, expected)
}
