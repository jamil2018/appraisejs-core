import fs from 'node:fs'
import { readValidationRegistry, renderValidationMatrix } from './lib/harness-validation.mjs'

const file = 'docs/agent-validation-matrix.md'
const begin = '<!-- development-harness-registry:start -->'
const end = '<!-- development-harness-registry:end -->'
const source = fs.readFileSync(file, 'utf8')
const generated = renderValidationMatrix(readValidationRegistry(process.cwd()))
const section = `${begin}\n${generated}\n${end}`
const start = source.indexOf(begin)
const finish = source.indexOf(end)
if (process.argv.includes('--write')) {
  if (start < 0)
    fs.writeFileSync(
      file,
      `${source}\n## Development validation registry\n\nGenerated by \`node scripts/check-harness-matrix.mjs --write\`; edit the registry instead of this table.\n\n${section}\n`,
    )
  else {
    if (finish < start) throw new Error('Invalid registry matrix markers')
    fs.writeFileSync(file, source.slice(0, start) + section + source.slice(finish + end.length))
  }
} else {
  const normalize = value => value.replace(/\s/g, '').replace(/-{3,}/g, '---').trim()
  if (start < 0 || finish < start || normalize(source.slice(start, finish + end.length)) !== normalize(section)) {
    throw new Error('Validation matrix differs from registry. Run node scripts/check-harness-matrix.mjs --write')
  }
  console.log('Validation matrix matches the registry.')
}
